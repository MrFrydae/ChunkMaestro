"""Full-verify regressions for ordinary and checked-in generated C# policy."""
import os
from pathlib import Path
import shutil
import subprocess
import sys
import tempfile

import build

HEADER = '// <auto-generated/>\n'
VALID = '''internal static class Fixture
{
    // Braces in comments {} and interpolation aren't code blocks.
    internal static string Read(int value) => $"{{literal}} {value}";
}
'''
CASES = [
    ('generated-var', '''internal static class Fixture
{
    internal static int Read()
    {
        var value = 1;
        return value;
    }
}
''', 'explicit C# types'),
    ('generated-allman', '''internal static class Fixture {
    internal static int Read()
    {
        return 1;
    }
}
''', 'Allman braces'),
    ('generated-statements', '''internal static class Fixture
{
    internal static int Read()
    {
        int value = 1; return value;
    }
}
''', 'one C# statement per line'),
    ('generated-empty-block', '''internal static class Fixture
{
    internal static void Run() { }
}
''', 'Allman braces'),
    ('generated-property', '''internal sealed class Fixture
{
    internal int Value { get; set; }
}
''', 'Allman braces'),
]


def main():
    with tempfile.TemporaryDirectory(prefix='chunkmaestro-style-policy-') as temporary:
        root = Path(temporary)
        for name in ('global.json', 'Directory.Build.props', 'Directory.Build.targets',
                     'Directory.Packages.props', 'NuGet.Config', '.editorconfig'):
            shutil.copyfile(build.ROOT / name, root / name)
        tooling = root / 'tooling/build'
        tooling.mkdir(parents=True)
        shutil.copyfile(build.ROOT / 'tooling/build/build.py', tooling / 'build.py')
        shutil.copytree(build.ROOT / 'tooling/build/StyleCheck', tooling / 'StyleCheck',
                        ignore=shutil.ignore_patterns('bin', 'obj'))
        project = root / 'src/Fixture'
        project.mkdir(parents=True)
        (project / 'Fixture.csproj').write_bytes(
            b'<Project Sdk="Microsoft.NET.Sdk"><PropertyGroup><TargetFramework>net10.0</TargetFramework></PropertyGroup></Project>\n')
        source = project / 'Fixture.g.cs'
        source.write_bytes((HEADER + VALID).encode('utf-8'))
        command = [sys.executable, str(tooling / 'build.py')]
        environment = {**os.environ, 'MSBUILDDISABLENODEREUSE': '1'}
        subprocess.run([*command, 'sync'], cwd=root, check=True, env=environment)
        subprocess.run([*command, 'update-locks'], cwd=root, check=True,
                       env={**environment, 'CI': 'false'})
        evidence = build.ROOT / '.artifacts/build'
        evidence.mkdir(parents=True, exist_ok=True)
        for name, code, diagnostic in [*CASES, ('generated-valid', VALID, None)]:
            expected = (HEADER + code).encode('utf-8')
            source.write_bytes(expected)
            result = subprocess.run([*command, 'verify'], cwd=root, capture_output=True, text=True, env=environment)
            output = result.stdout + result.stderr
            (evidence / (name + '.log')).write_text(output, encoding='utf-8')
            assert source.read_bytes() == expected, 'Verification modified source.'
            if diagnostic:
                if result.returncode == 0 or diagnostic not in output:
                    raise RuntimeError('Generated C# policy fixture was not rejected: ' + name)
            elif result.returncode:
                raise RuntimeError('Valid generated C# was rejected; inspect fixture log.')
        print('PASS: full verify rejects generated var, declaration-line braces, multiple statements, empty blocks and compact properties; valid interpolation/comments accepted; source unchanged.')


if __name__ == '__main__':
    main()
